// Writes the small script that runs in every subframe instead of the full cookie-banner script.
//
// The full script (autoconsent.js, ~556 KB) only goes into main frames. A few consent managers
// draw their banner inside an iframe, so subframes get this gate: it checks the frame's URL
// against the rules that run in frames (plus Sourcepoint's message frames, which autoconsent
// detects in code), and for the URL-less frame rules looks for their banner element. On a match
// it asks the app, which loads the full script into that one frame.
//
// Usage (from build.sh): node tools/autoconsent/frame-gate.mjs <autoconsent package dir> <out.js>
import fs from 'node:fs';
import path from 'node:path';

const [pkg, out] = process.argv.slice(2);
const dirs = ['rules/autoconsent', 'rules/generated'].map((d) => path.join(pkg, d));
const rules = dirs.flatMap((d) =>
    fs.readdirSync(d).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(fs.readFileSync(path.join(d, f), 'utf8'))),
);

const patterns = new Set();
const selectors = new Set();
for (const rule of rules) {
    if (rule.runContext?.frame !== true) continue;
    if (rule.runContext.urlPattern) {
        patterns.add(rule.runContext.urlPattern);
        continue;
    }
    const found = (rule.detectCmp ?? []).map((s) => s.exists).filter((s) => typeof s === 'string');
    if (found.length === 0) throw new Error(`Frame rule "${rule.name}" has no urlPattern or "exists" selector to gate on`);
    found.forEach((s) => selectors.add(s));
}

// Sourcepoint's frame CMP (lib/cmps/sourcepoint-frame.ts) checks these in code, not in a rule.
const sourcepoint = String.raw`^https?://ccpa-(notice|pm)\.sp-prod\.net/|/(index|privacy-manager/index|ccpa_pm/index|us_pm/index)\.html\?(.*&)?(message_id|requestUUID|consentUUID)=`;
patterns.add(sourcepoint);

const source = `/*! Browsa cookie-banner frame gate, generated by tools/autoconsent/frame-gate.mjs */
(function () {
  if (window.top === window || window.autoconsentReceiveMessage) return;
  var patterns = ${JSON.stringify([...patterns])};
  var selector = ${JSON.stringify([...selectors].join(','))};
  var asked = false;
  function ask() {
    if (asked) return;
    asked = true;
    window.webkit.messageHandlers.autoconsent.postMessage({ type: 'loadFrame' });
  }
  var href = location.href;
  for (var i = 0; i < patterns.length; i++) {
    try { if (new RegExp(patterns[i]).test(href)) return ask(); } catch (e) {}
  }
  if (!selector) return;
  function look() { if (!asked && document.querySelector(selector)) ask(); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', look);
  else look();
  setTimeout(look, 1000);
  setTimeout(look, 3000);
})();
`;
fs.writeFileSync(out, source);
console.log(`Wrote ${out} (${patterns.size} URL patterns, ${selectors.size} selectors)`);
